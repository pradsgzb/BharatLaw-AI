"""Authorization-shaped retrieval requests and deterministic reciprocal-rank fusion.

No network calls are made here. The production query gateway must build Scope
from authenticated server-side policy, select a concrete permitted index, and
reauthorize evidence from the canonical repository before model transmission.
"""
from __future__ import annotations
from dataclasses import dataclass
from math import isfinite
from typing import Iterable, Sequence

@dataclass(frozen=True)
class Scope:
    embedding_profile: str
    language: str = "en"
    release_id: str | None = None
    source_ids: tuple[str, ...] = ()
    tenant_id: str | None = None
    workspace_id: str | None = None
    acl_revision: int | None = None
    permitted_document_types: tuple[str, ...] = ()

    def filters(self) -> list[dict]:
        if not self.embedding_profile or self.language not in {"en", "hi"}:
            raise ValueError("An approved embedding profile and language are required")
        base = [
            {"term": {"embedding_profile": self.embedding_profile}},
            {"term": {"language": self.language}},
            {"term": {"is_synthetic": False}},
        ]
        private = self.tenant_id is not None or self.workspace_id is not None or self.acl_revision is not None
        if private:
            if not self.tenant_id or not self.workspace_id or not self.acl_revision or self.acl_revision < 1:
                raise ValueError("Private scope requires tenant, workspace, and current ACL revision")
            if self.release_id is not None or self.source_ids or self.permitted_document_types:
                raise ValueError("Do not mix private and public index scopes")
            base += [
                {"term": {"tenant_id": self.tenant_id}},
                {"term": {"workspace_id": self.workspace_id}},
                {"term": {"acl_revision": self.acl_revision}},
                {"term": {"state": "active"}},
            ]
        else:
            if not self.release_id:
                raise ValueError("Public scope requires a pinned corpus release")
            base += [
                {"term": {"corpus_release_id": self.release_id}},
                {"term": {"published": True}},
                {"term": {"restricted": False}},
                {"terms": {"source_id": list(self.source_ids)}} if self.source_ids else {"match_none": {}},
            ]
            if self.permitted_document_types:
                base.append({"terms": {"document_type": list(self.permitted_document_types)}})
        return base

def validate_vector(vector: Sequence[float], dimensions: int) -> list[float]:
    if dimensions <= 0 or len(vector) != dimensions:
        raise ValueError("Embedding dimensions do not match the approved index profile")
    if any(isinstance(v, bool) or not isinstance(v, (int, float)) for v in vector):
        raise ValueError("Embedding elements must be finite real numbers")
    values = [float(v) for v in vector]
    if not all(isfinite(v) for v in values) or not any(v != 0.0 for v in values):
        raise ValueError("A cosine embedding must be finite and nonzero")
    return values

def build_queries(question: str, vector: Sequence[float], scope: Scope,
                  *, dimensions: int, candidates: int = 80) -> tuple[dict, dict]:
    if not isinstance(question, str) or not question.strip() or len(question) > 12000:
        raise ValueError("Invalid question")
    if isinstance(candidates, bool) or not 1 <= candidates <= 200:
        raise ValueError("Candidate budget must be between 1 and 200")
    filters = scope.filters()
    values = validate_vector(vector, dimensions)
    lexical = {
        "size": candidates, "_source": {"excludes": ["embedding"]},
        "query": {"bool": {
            "must": [{"multi_match": {
                "query": question, "fields": ["title^3", "heading_path^2", "search_text"],
                "type": "best_fields"}}],
            "filter": filters,
        }},
    }
    vector_query = {
        "size": candidates, "_source": {"excludes": ["embedding"]},
        "query": {"knn": {"embedding": {
            "vector": values, "k": candidates,
            "filter": {"bool": {"filter": filters}},
        }}},
    }
    # Safe date constraints, when used, must be generated by a typed policy
    # module and added identically inside both branches. Statutory applicability
    # is resolved from reviewed canonical assertions, NOT publication_date alone.
    return lexical, vector_query

def reciprocal_rank_fusion(rankings: Sequence[Iterable[str]], *, constant: int = 60,
                           limit: int = 80) -> list[tuple[str, float]]:
    if constant < 1 or limit < 1:
        raise ValueError("RRF constant and result limit must be positive")
    scores: dict[str, float] = {}
    for ranking in rankings:
        seen: set[str] = set()
        rank = 0
        for candidate_id in ranking:
            if not isinstance(candidate_id, str) or not candidate_id:
                raise ValueError("Every candidate must have a nonempty stable ID")
            if candidate_id in seen:
                continue
            seen.add(candidate_id)
            rank += 1
            scores[candidate_id] = scores.get(candidate_id, 0.0) + 1.0 / (constant + rank)
    return sorted(scores.items(), key=lambda pair: (-pair[1], pair[0]))[:limit]
